"""Generate a reading copy from authoritative TeX; standard library only."""
from pathlib import Path
import re,hashlib,json
P=Path(__file__).resolve().parent;src=(P/'main.tex').read_text()
def braces(s,start):
 assert s[start]=='{';level=0
 for i in range(start,len(s)):
  if i and s[i-1]=='\\':continue
  if s[i]=='{':level+=1
  elif s[i]=='}':
   level-=1
   if level==0:return s[start+1:i],i+1
 raise ValueError('unclosed brace')
def field(s,cmd):return braces(s,s.index(cmd)+len(cmd))[0]
aux=(P/'main.aux').read_text();refs=dict(re.findall(r'\\newlabel\{([^}]+)\}\{\{([^}]+)\}',aux));cites=dict(re.findall(r'\\bibcite\{([^}]+)\}\{([^}]+)\}',aux))
def text(s):
 s=re.sub(r'\\cite\{([^}]+)\}',lambda m:'['+', '.join(cites[k] for k in m[1].split(','))+']',s)
 s=re.sub(r'\\ref\{([^}]+)\}',lambda m:refs[m[1]],s);s=re.sub(r'\\label\{[^}]+\}','',s)
 s=s.replace(r'\unskip','').replace(r'\,',' ').replace('~',' ').replace(r'\%','%').replace('---','—').replace('--','–')
 for cmd,wrap in [('emph','*'),('textbf','**'),('textit','*')]:
  while '\\'+cmd+'{' in s:
   st=s.index('\\'+cmd+'{');v,end=braces(s,st+len(cmd)+1);s=s[:st]+wrap+v+wrap+s[end:]
 return s.strip()
def tab(s):
 pos=s.index(r'\begin{tabular}')+len(r'\begin{tabular}');_,end=braces(s,pos);s=s[end:];s=s.replace(r'\end{tabular}','')
 for k in ['toprule','midrule','bottomrule']:s=s.replace('\\'+k,'')
 s=s.replace(r'\multicolumn{2}{c}{lateral, ground, diagonal}','lateral, ground, diagonal & lateral, ground, diagonal')
 rows=[[text(c) for c in r.strip().split('&')] for r in s.split('\\\\') if r.strip()]
 return '\n'.join(['| '+' | '.join(rows[0])+' |','| '+' | '.join(['---']*len(rows[0]))+' |']+['| '+' | '.join(r)+' |' for r in rows[1:]])
def figure(m):
 b=m[0];name=re.search(r'\\includegraphics\[[^]]+\]\{([^}]+)\}',b)[1];cap=text(field(b,r'\caption'));label=field(b,r'\label')
 return '\n\n![Figure '+refs[label]+']('+name.replace('.pdf','.png')+')\n\nFigure '+refs[label]+'. '+cap+'\n\n'
def table(m):
 b=m[0];cap=text(field(b,r'\caption'));label=field(b,r'\label');f=re.search(r'\\input\{([^}]+)\}',b)
 body=(P/f[1]).read_text() if f else b[b.index(r'\begin{tabular}'):b.index(r'\end{tabular}')+len(r'\end{tabular}')]
 return '\n\nTable '+refs[label]+'. '+cap+'\n\n'+tab(body)+'\n\n'
s=src.split(r'\maketitle',1)[1].split(r'\clearpage',1)[0]
s=re.sub(r'\\begin\{figure\*?\}.*?\\end\{figure\*?\}',figure,s,flags=re.S)
s=re.sub(r'\\begin\{table\*?\}.*?\\end\{table\*?\}',table,s,flags=re.S)
s=re.sub(r'\\input\{([^}]+)\}',lambda m:(P/m[1]).read_text(),s)
s=s.replace(r'\begin{abstract}','## Abstract\n').replace(r'\end{abstract}','');s=re.sub(r'\\section\{([^}]+)\}',r'## \1',s);s=re.sub(r'\\subsection\{([^}]+)\}',r'### \1',s)
s=s.replace(r'\begin{itemize}','').replace(r'\end{itemize}','').replace(r'\item','\n- ');s=s.replace(r'\begin{equation}','\n$$\n').replace(r'\end{equation}','\n$$\n');s=re.sub(r'\n{3,}','\n\n',text(s))
bbl=(P/'main.bbl').read_text();items=re.split(r'\\bibitem\{([^}]+)\}',bbl)[1:];bib=[]
for i in range(0,len(items),2):
 key,val=items[i:i+2];val=val.split(r'\end{thebibliography}')[0];val=re.sub(r'\\BIBentry[A-Za-z]+','',val);val=val.replace(r'\newblock',' ');val=re.sub(r'\\url\{([^}]+)\}',r'\1',val);val=val.replace(r'\relax','');val=text(val).replace('{','').replace('}','');bib.append('['+cites[key]+'] '+re.sub(r'\s+',' ',val))
header='<!-- GENERATED by sync_markdown.py; edit main.tex, not this reading copy. -->\n\n# '+text(field(src,r'\title'))+'\n\n'
(P/'DAC_REWRITE.md').write_text(header+s+'\n\n## References\n\n'+'\n\n'.join(bib)+'\n')
(P/'SOURCE_SYNC.json').write_text(json.dumps({'authoritative':'main.tex','main_tex_sha256':hashlib.sha256(src.encode()).hexdigest(),'reading_md_sha256':hashlib.sha256((P/'DAC_REWRITE.md').read_bytes()).hexdigest()},indent=2)+'\n')
